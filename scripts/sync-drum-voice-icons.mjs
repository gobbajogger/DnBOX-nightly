// Port the native R22 voice path stream losslessly; no substitute icon artwork.
import {readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {join} from 'node:path';
const [root,mode]=process.argv.slice(2);
if(!root||mode&&mode!=='--check')throw Error('Usage: node scripts/sync-drum-voice-icons.mjs <firmware> [--check]');
const path='firmware/src/app';
const src=readFileSync(join(root,path,'ui_drum_voice.inc'),'utf8');
const ui=readFileSync(join(root,path,'ui.c'),'utf8');
const array=name=>{
 const match=src.match(new RegExp('\\b'+name+'\\[[^=]+?=\\s*\\{([\\s\\S]+?)\\};'));
 if(!match)throw Error('Missing native '+name);
 return match[1];
};
const ints=text=>[...text.matchAll(/\d+/g)].map(m=>Number(m[0]));
const xy=ints(array('DV_XY_PACKED')),packed=ints(array('DV_POLY_PACKED'));
const rows=ints(array('DV_BODY')), labels=[...array('DV_VOICE_NAMES').matchAll(/"([A-Z ]+)"/g)].map(m=>m[1]);
const tail=ints(array('DV_808_TAIL'));
if(rows.length!==44||labels.length!==13||tail.length!==4)throw Error('Unexpected native drum roster');
const draw=ui.match(/static UI_DRAW void draw_drum\(int band\)\s*\{([\s\S]+?)\n\}/)?.[1];
if(!draw?.includes('dv_body_pictogram')||!draw.includes('.26f, env')||!draw.includes('cv_line(7, y + 5 + 3*c, 12, y + 1 + 3*c, C_WHITE)')||
 !draw.includes('cv_line(12, y + 1 + 3*c, 17, y + 5 + 3*c, C_WHITE)'))throw Error('Native selected row or Accent geometry changed');
function voice(first,count){
 const parts=[];
 for(let j=first;j<first+count;j++){
  const bit=j*17,at=bit>>3;
  if(packed[at+2]===undefined)throw Error('Truncated native polyline');
  const stream=((packed[at]|packed[at+1]<<8|packed[at+2]<<16) >>> (bit&7)) & 0x1ffff;
  let offset=stream&2047;
  const n=stream>>11;
  if(n<2||n>64)throw Error('Unexpected native polyline length');
  const coord=()=>{
   const a=xy[offset++];
   if(a===undefined||a>=128&&xy[offset]===undefined)throw Error('Truncated native coordinate');
   return a<128?(a+8)*100:((a&127)<<8)|xy[offset++];
  };
  parts.push(Array.from({length:n},(_,i)=>(i?'L':'M')+coord()+' '+coord()).join(''));
 }
 return parts.join('');
}
const sets=['909','808'].map((kit,k)=>Array.from({length:11},(_,i)=>{
 const j=2*(11*k+i);
 return [labels[k&&i>=7?tail[i-7]:i],voice(rows[j],rows[j+1])];
}));
const sha=execFileSync('git',['-C',root,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
const output='// SPDX-License-Identifier: GPL-3.0-only\n// Generated by scripts/sync-drum-voice-icons.mjs from DnBOX '+sha+' ui_drum_voice.inc\nexport const DRUM_VOICE_GEOMETRY = '+JSON.stringify({'909':sets[0],'808':sets[1]},null,2)+';\n';
const dest=new URL('../web/product-site/remote/drum-voice-icons.generated.mjs',import.meta.url);
if(mode==='--check'){if(readFileSync(dest,'utf8')!==output)throw Error('Native drum voice geometry differs');}
else writeFileSync(dest,output);
